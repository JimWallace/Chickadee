// APIServer/Services/SuiteAnchorPinning.swift
//
// Pins a hand-written test to the notebook cell that defines a name, or
// clears the pin (notebook views NB7, "Pin to a cell"). The pin is rule 1 of
// the anchoring (docs/notebook-guide.md, "Anchors"): `TestSuiteEntry.anchor`.
// A generated test is anchored by its check or family, so it cannot be
// pinned. Grading never reads a pin, so a pin does not close, re-validate or
// retest anything.
//
// Shared by `PUT /instructor/:assignmentID/suite-anchor` and the MCP
// `update_suite` tool, so both doors refuse the same tests with the same
// words.

import Core
import Fluent
import Foundation

enum SuiteAnchorPinning {
    enum PinError: Error, Equatable, Sendable {
        /// The suite has no test with this filename.
        case unknownScript(String)
        /// The test is generated by a family or a notebook check.
        case generated(String)

        var message: String {
            switch self {
            case .unknownScript(let script):
                return "The suite has no test named '\(script)'."
            case .generated(let script):
                return "'\(script)' is generated, so its check or family names its cell."
            }
        }
    }

    /// One pin to write: the test's filename and the anchor name, or nil to
    /// clear the pin.
    struct Pin: Equatable, Sendable {
        let script: String
        let anchor: String?
    }

    /// A requested anchor as stored: trimmed, and nil when nothing is left.
    static func normalized(_ anchor: String?) -> String? {
        let trimmed = anchor?.trimmingCharacters(in: .whitespacesAndNewlines)
        return (trimmed?.isEmpty == false) ? trimmed : nil
    }

    /// The first pin the manifest would refuse, or nil when every pin can be
    /// written. A caller that saves something else before the pins checks
    /// first, so a refused pin cannot leave that save half done.
    static func refusal(of pins: [Pin], in props: TestProperties) -> PinError? {
        for pin in pins {
            guard let entry = props.testSuites.first(where: { $0.script == pin.script }) else {
                return .unknownScript(pin.script)
            }
            if entry.isGenerated { return .generated(pin.script) }
        }
        return nil
    }

    /// Writes every pin in one manifest edit, or none: an unknown or a
    /// generated test refuses the whole edit. Each anchor is normalized.
    static func apply(_ pins: [Pin], setup: APITestSetup, on db: any Database) async throws {
        guard !pins.isEmpty else { return }
        try await mutateManifest(setup: setup, on: db) { props in
            if let refusal = refusal(of: pins, in: props) { throw refusal }
            for pin in pins {
                guard let index = props.testSuites.firstIndex(where: { $0.script == pin.script }) else { continue }
                props.testSuites[index].anchor = normalized(pin.anchor)
            }
        }
    }
}
