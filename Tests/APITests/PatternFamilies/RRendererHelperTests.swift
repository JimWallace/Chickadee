// Tests/APITests/PatternFamilies/RRendererHelperTests.swift
//
// The pure helpers behind the R pattern-family renderer: the per-case call
// context (omitted arguments switch the rest of the call to named arguments),
// the expected-value expression, the per-student preamble and the type-name
// map. The execution suite needs Rscript; these run anywhere.

import Core
import Foundation
import Testing

@testable import APIServer

@Suite struct RRendererHelperTests {

    private static func family(paramNames: [String], cases: [PatternCase]) -> PatternFamily {
        PatternFamily(
            id: "fam", name: "Family", kind: .boundaryEquality, functionName: "f",
            paramNames: paramNames, cases: cases)
    }

    // MARK: - rCallContext

    @Test func aGapSwitchesTheRestOfTheCallToNamedArguments() {
        let c = PatternCase(
            key: "01", label: "", args: [.int(1), .int(2), .int(3)], expected: .int(0),
            argsProvided: [true, false, true])
        let context = rCallContext(for: Self.family(paramNames: ["a", "b", "c"], cases: [c]), case: c)

        // R matches positionally until the gap; after it, only a name binds
        // the value to the right parameter.
        #expect(context.callArgs == "a, c = c")
        #expect(context.declBlock == "a <- 1\nc <- 3\n\n")
        #expect(!context.declBlock.contains("b <-"))
    }

    @Test func everyArgumentOmittedGivesNoInputLine() {
        let c = PatternCase(
            key: "01", label: "", args: [.int(1)], expected: .int(0), argsProvided: [false])
        let context = rCallContext(for: Self.family(paramNames: ["a"], cases: [c]), case: c)

        #expect(context.callArgs.isEmpty)
        #expect(context.declBlock.isEmpty)
        #expect(context.inputLine == "\"\(GeneratedMessage.input)(no input)\\n\",")
    }

    @Test func aVariableReferenceBindsTheNameNotTheLiteral() {
        let c = PatternCase(
            key: "01", label: "", args: [.int(0), .string("x")], expected: .int(0),
            argVarRefs: ["patient_data", nil])
        let context = rCallContext(for: Self.family(paramNames: ["df", "col"], cases: [c]), case: c)

        #expect(context.declBlock.contains("df <- patient_data\n"))
        #expect(context.declBlock.contains("col <- \"x\""))
        #expect(context.callArgs == "df, col")
        #expect(context.inputLine.contains("\"df=\", chickadee_format(df)"))
        #expect(context.inputLine.hasSuffix("\"\\n\","))
    }

    @Test func aNonSyntacticParameterNameIsBacktickQuoted() {
        let c = PatternCase(key: "01", label: "", args: [.int(1)], expected: .int(0))
        let context = rCallContext(for: Self.family(paramNames: ["_x"], cases: [c]), case: c)

        #expect(context.declBlock == "`_x` <- 1\n\n")
        #expect(context.callArgs == "`_x`")
    }

    // MARK: - rExpectedExpression

    @Test func expectedExpressionPrefersTheVariableReference() {
        let byRef = PatternCase(key: "01", label: "", args: [], expected: .int(5), expectedVarRef: "target")
        #expect(rExpectedExpression(for: byRef) == "target")

        let emptyRef = PatternCase(key: "02", label: "", args: [], expected: .int(5), expectedVarRef: "")
        #expect(rExpectedExpression(for: emptyRef) == "5", "an empty reference falls back to the literal")

        let literal = PatternCase(key: "03", label: "", args: [], expected: .bool(true))
        #expect(rExpectedExpression(for: literal) == "TRUE")
    }

    // MARK: - rPersonalizationPreambleForCase

    @Test func preambleIsEmptyWhenTheCaseUsesNoPerStudentName() {
        let c = PatternCase(
            key: "01", label: "", args: [.int(1)], expected: .int(0), argVarRefs: ["shared"])
        #expect(rPersonalizationPreambleForCase(c, perStudentNames: []).isEmpty)
        #expect(rPersonalizationPreambleForCase(c, perStudentNames: ["other"]).isEmpty)
    }

    @Test func preambleBindsEachPerStudentNameAndFailsClosed() throws {
        let c = PatternCase(
            key: "01", label: "", args: [.int(1), .int(2)], expected: .int(0),
            argVarRefs: ["weight", "shared"], expectedVarRef: "bmi")
        let preamble = rPersonalizationPreambleForCase(c, perStudentNames: ["weight", "bmi"])

        #expect(preamble.contains(".ck_inputs_values <- chickadee_inputs()"))
        #expect(preamble.contains("bmi <- .ck_inputs_values[[\"bmi\"]]"))
        #expect(preamble.contains("weight <- .ck_inputs_values[[\"weight\"]]"))
        #expect(preamble.contains("if (is.null(.ck_inputs_values[[\"weight\"]]))"))
        #expect(preamble.contains("Personalization input 'weight' is unavailable"))
        #expect(!preamble.contains("shared"), "a name that is not per-student stays a shared variable")

        // Sorted, so the generated bytes are stable.
        let bmi = try #require(preamble.range(of: "bmi <- "))
        let weight = try #require(preamble.range(of: "weight <- "))
        #expect(bmi.lowerBound < weight.lowerBound)
    }

    // MARK: - rTypeCheckExpression

    @Test(arguments: [
        ("numeric", "is.numeric(v)"), ("float", "is.numeric(v)"), ("integer", "is.numeric(v)"),
        ("str", "is.character(v)"), ("String", "is.character(v)"),
        ("bool", "is.logical(v)"), ("LOGICAL", "is.logical(v)"),
        ("dict", "is.list(v)"), ("list", "is.list(v)"),
        ("callable", "is.function(v)"), ("function", "is.function(v)"),
        ("DataFrame", "is.data.frame(v)"), ("data.frame", "is.data.frame(v)"),
        ("factor", "is.factor(v)"), ("matrix", "is.matrix(v)"), ("vector", "is.vector(v)"),
        ("None", "is.null(v)"), ("null", "is.null(v)"),
        ("any", "TRUE"), ("object", "TRUE"),
    ])
    func typeNamesMapToRPredicates(typeName: String, expected: String) {
        #expect(rTypeCheckExpression(typeName: typeName, valueExpr: "v") == expected)
    }

    @Test func anUnknownTypeNameBecomesAnInheritsCheck() {
        #expect(rTypeCheckExpression(typeName: "tbl_df", valueExpr: "result") == "inherits(result, \"tbl_df\")")
    }

    // MARK: - rIdentifier

    @Test func identifierQuotingRules() {
        #expect(rIdentifier("x") == "x")
        #expect(rIdentifier(".hidden") == ".hidden")
        #expect(rIdentifier("a.b_c2") == "a.b_c2")
        #expect(rIdentifier("2x") == "`2x`")
        #expect(rIdentifier("has space") == "`has space`")
        #expect(rIdentifier("a`b c") == "`ab c`", "a backtick inside the name is removed, not escaped")
        #expect(rIdentifier("") == "`_`")
    }
}
