#!/usr/bin/env bash
set -euo pipefail

# Every first-party Public/*.js file opts in to type checking (#2782).
#
# jsconfig.json sets checkJs to false, so tsc checks only the files that start
# with a `// @ts-check` line. scripts/typecheck-js.sh runs tsc. This guard
# makes sure the set of checked files only grows:
#
#   * A Public/*.js file must have `// @ts-check` as its first line, unless
#     scripts/ts-check-pending.txt lists it.
#   * A pending entry for a file that already opts in, or that no longer
#     exists, is an error. The list is a ratchet: it only shrinks.
#
# The guard reads only the files. It does not need node, so it runs in the
# format-lint job.

repo_root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$repo_root"

pending_file="scripts/ts-check-pending.txt"

# Files that cannot opt in, and why. One per line: path|reason.
EXEMPT='Public/runner-support-sources.js|Generated by scripts/generate-js-constants.sh. A hand edit fails its --check.'

is_exempt() {
  printf '%s\n' "$EXEMPT" | cut -d'|' -f1 | grep -qxF "$1"
}

opts_in() {
  [ "$(head -n 1 "$1")" = "// @ts-check" ]
}

pending="$(grep -vE '^[[:space:]]*(#|$)' "$pending_file" || true)"

is_pending() {
  printf '%s\n' "$pending" | grep -qxF "$1"
}

status=0

for f in Public/*.js; do
  is_exempt "$f" && continue
  is_pending "$f" && continue
  if ! opts_in "$f"; then
    echo "check-ts-check-optin: $f does not opt in to type checking." >&2
    echo "  Make \`// @ts-check\` its first line and run scripts/typecheck-js.sh." >&2
    status=1
  fi
done

while IFS= read -r f; do
  [ -z "$f" ] && continue
  if [ ! -f "$f" ]; then
    echo "check-ts-check-optin: stale pending entry: $f does not exist." >&2
    echo "  Remove its line from $pending_file." >&2
    status=1
  elif opts_in "$f"; then
    echo "check-ts-check-optin: stale pending entry: $f already opts in." >&2
    echo "  Remove its line from $pending_file." >&2
    status=1
  fi
done <<<"$pending"

if [ "$status" -eq 0 ]; then
  count="$(printf '%s\n' "$pending" | grep -c . || true)"
  echo "check-ts-check-optin: OK ($count files pending)"
fi
exit "$status"
