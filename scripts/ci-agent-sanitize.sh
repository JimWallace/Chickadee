#!/usr/bin/env bash
# scripts/ci-agent-sanitize.sh
#
# Cleans the text that a CI agent wrote, before a job with no model posts it
# to GitHub. Every agent workflow uses this one script, so the rules cannot
# drift between copies (#2711).
#
#   scripts/ci-agent-sanitize.sh [options] INPUT OUTPUT
#   scripts/ci-agent-sanitize.sh --self-test
#
# What it does, in this order:
#   1. Refuses text that looks like a credential: an Anthropic key, a GitHub
#      token, a JWT or a private key. It writes nothing and exits 3.
#   2. Keeps at most --max-lines lines, and cuts each line to --max-width
#      characters.
#   3. Keeps whole lines up to --max-chars bytes. When it cuts here, it adds
#      the --cut-note line (or a default note).
#   4. Breaks each @mention with a zero-width space, so that the post pings
#      nobody, and turns each Markdown image into a plain link, so that no
#      reader's browser fetches a URL that the agent chose.
#   5. Adds each --append line (a run link, a marker), then the "Generated by
#      Claude Code" footer.
#
# Options:
#   --max-lines N    default: no limit
#   --max-width N    default: no limit
#   --max-chars N    default: 60000 (a GitHub comment or issue body holds
#                    at most 65,536 characters)
#   --cut-note TEXT  the line to add when --max-chars cuts the text
#   --append TEXT    a line to add after the text; repeatable
#
# Exit status: 0 when OUTPUT is written, 1 when INPUT is empty or missing
# (OUTPUT is not written), 2 on a usage error, 3 on a credential.
#
# Bash, grep, sed, awk, head and cut only: it runs on the plain Swift image
# in format-lint and on macOS.

set -uo pipefail

readonly credential_pattern='sk-ant-|gh[pousr]_[A-Za-z0-9]{20,}|github_pat_|eyJ[A-Za-z0-9_-]{20,}\.|BEGIN [A-Z ]*PRIVATE KEY'
readonly footer='_Generated by [Claude Code](https://claude.ai/code)_'

usage() {
  echo "usage: $0 [--max-lines N] [--max-width N] [--max-chars N] [--cut-note TEXT] [--append TEXT]... INPUT OUTPUT" >&2
  echo "       $0 --self-test" >&2
  exit 2
}

is_count() {
  case "$1" in '' | *[!0-9]*) return 1 ;; *) return 0 ;; esac
}

sanitize() {
  local max_lines="" max_width="" max_chars=60000
  local cut_note="_The text is cut here, because it is too long._"
  local appends=()
  while [ $# -gt 0 ]; do
    case "$1" in
      --max-lines | --max-width | --max-chars)
        if [ $# -lt 2 ] || ! is_count "$2"; then usage; fi
        case "$1" in
          --max-lines) max_lines="$2" ;;
          --max-width) max_width="$2" ;;
          --max-chars) max_chars="$2" ;;
        esac
        shift 2
        ;;
      --cut-note)
        [ $# -ge 2 ] || usage
        cut_note="$2"
        shift 2
        ;;
      --append)
        [ $# -ge 2 ] || usage
        appends+=("$2")
        shift 2
        ;;
      --*) usage ;;
      *) break ;;
    esac
  done
  [ $# -eq 2 ] || usage
  local input="$1" output="$2"

  if [ ! -s "$input" ]; then
    echo "ci-agent-sanitize: the agent text is empty." >&2
    return 1
  fi
  if grep -qE -- "$credential_pattern" "$input"; then
    echo "ci-agent-sanitize: the agent text looks like it holds a credential. Nothing was written." >&2
    return 3
  fi

  local zwsp
  zwsp="$(printf '\342\200\213')"
  # Byte counts, not characters: a byte budget is never over GitHub's
  # character limit, and it is the same in every locale.
  LC_ALL=C awk -v max_lines="$max_lines" -v max_width="$max_width" \
    -v max_chars="$max_chars" -v note="$cut_note" '
    max_lines != "" && NR > max_lines + 0 { exit }
    {
      line = $0
      if (max_width != "") line = substr(line, 1, max_width + 0)
      total += length(line) + 1
      if (total > max_chars + 0) { print ""; print note; exit }
      print line
    }
  ' "$input" | sed -e "s/@/@${zwsp}/g" -e 's/!\[/[/g' > "$output"

  {
    if [ "${#appends[@]}" -gt 0 ]; then
      echo
      printf '%s\n' "${appends[@]}"
    fi
    echo
    echo "---"
    echo "$footer"
  } >> "$output"
}

# --- self-test ---------------------------------------------------------------

self_test() {
  local tmp failures=0 status
  tmp="$(mktemp -d)"
  local zwsp
  zwsp="$(printf '\342\200\213')"

  pass() { echo "ok   $1"; }
  fail() { echo "FAIL $1"; failures=$((failures + 1)); }

  # Runs sanitize on the text in $2 with the remaining options, and leaves the
  # status in $status and the output in $tmp/out.
  run() {
    local text="$1"
    shift
    printf '%s' "$text" > "$tmp/in"
    rm -f "$tmp/out"
    (sanitize "$@" "$tmp/in" "$tmp/out") 2> "$tmp/err"
    status=$?
  }

  run $'### Report\n\nAll good.\n'
  if [ "$status" -eq 0 ] && head -n 1 "$tmp/out" | grep -qx '### Report' \
    && [ "$(tail -n 1 "$tmp/out")" = "$footer" ] && [ "$(tail -n 2 "$tmp/out" | head -n 1)" = "---" ]; then
    pass "plain text keeps its body and gets the footer"
  else
    fail "plain text keeps its body and gets the footer (status $status)"
  fi

  for secret in 'sk-ant-api03-abcdef' 'ghp_abcdefghijklmnopqrstuvwxyz0123' 'ghs_abcdefghijklmnopqrstuvwxyz0123' \
    'github_pat_11ABCDEF' 'eyJhbGciOiJIUzI1NiIsInR5cCI6.eyJzdWIiOiIx' '-----BEGIN OPENSSH PRIVATE KEY-----'; do
    run "Before $secret after"$'\n'
    if [ "$status" -eq 3 ] && [ ! -e "$tmp/out" ]; then
      pass "refuses ${secret:0:12}"
    else
      fail "refuses ${secret:0:12} (status $status)"
    fi
  done

  run ''
  if [ "$status" -eq 1 ] && [ ! -e "$tmp/out" ]; then pass "empty input writes nothing"; else fail "empty input writes nothing (status $status)"; fi

  run $'Ask @octocat and @JimWallace.\n'
  if [ "$status" -eq 0 ] && grep -qF "@${zwsp}octocat and @${zwsp}JimWallace" "$tmp/out"; then
    pass "breaks @mentions"
  else
    fail "breaks @mentions"
  fi

  run $'See ![chart](https://example.com/x.png) here.\n'
  if [ "$status" -eq 0 ] && grep -qF 'See [chart](https://example.com/x.png) here.' "$tmp/out" && ! grep -qF '![' "$tmp/out"; then
    pass "turns an image into a link"
  else
    fail "turns an image into a link"
  fi

  run $'one\ntwo\nthree\nfour\n' --max-lines 2
  if [ "$status" -eq 0 ] && grep -qx two "$tmp/out" && ! grep -qx three "$tmp/out"; then
    pass "--max-lines keeps the first lines"
  else
    fail "--max-lines keeps the first lines"
  fi

  run $'abcdefghij\n' --max-width 4
  if [ "$status" -eq 0 ] && head -n 1 "$tmp/out" | grep -qx abcd; then
    pass "--max-width cuts long lines"
  else
    fail "--max-width cuts long lines"
  fi

  run $'aaaaaaaaa\nbbbbbbbbb\nccccccccc\n' --max-chars 20 --cut-note 'CUT HERE'
  if [ "$status" -eq 0 ] && grep -qx bbbbbbbbb "$tmp/out" && ! grep -q ccc "$tmp/out" && grep -qx 'CUT HERE' "$tmp/out"; then
    pass "--max-chars cuts on a whole line and adds the note"
  else
    fail "--max-chars cuts on a whole line and adds the note"
  fi

  run $'short\n' --max-chars 20 --cut-note 'CUT HERE'
  if [ "$status" -eq 0 ] && ! grep -q 'CUT HERE' "$tmp/out"; then
    pass "no note when nothing is cut"
  else
    fail "no note when nothing is cut"
  fi

  run $'Body\n' --append 'Run: https://example.com/run/1' --append '<!-- marker -->'
  if [ "$status" -eq 0 ] && grep -qx 'Run: https://example.com/run/1' "$tmp/out" \
    && [ "$(tail -n 4 "$tmp/out" | head -n 1)" = '<!-- marker -->' ]; then
    pass "--append lines come after the text and before the footer"
  else
    fail "--append lines come after the text and before the footer"
  fi

  run $'Body\n' --max-lines
  if [ "$status" -eq 2 ]; then pass "a flag with no value is a usage error"; else fail "a flag with no value is a usage error (status $status)"; fi

  run $'Body\n' --max-lines ten
  if [ "$status" -eq 2 ]; then pass "a count that is not a number is a usage error"; else fail "a count that is not a number is a usage error (status $status)"; fi

  rm -rf "$tmp"
  if [ "$failures" -ne 0 ]; then
    echo "ci-agent-sanitize self-test: $failures failure(s)"
    return 1
  fi
  echo "ci-agent-sanitize self-test: OK"
}

case "${1:-}" in
  --self-test) self_test ;;
  *) sanitize "$@" ;;
esac
